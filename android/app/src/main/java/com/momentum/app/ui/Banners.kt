const val HYPERSPACE = "hyperspace"
const val ULTRA_HYPERSPACE = "ultrahyperspace"

/** Selectable banners in display order (the hyperspace easter egg comes on top when unlocked). */
val BANNERS: List<String> = DEFS.keys.filter { it != HYPERSPACE && it != ULTRA_HYPERSPACE }

private val PASTEL = setOf("cottoncandy", "hearts", "strawberry", "meadow", "glitter", "lavender", "balloons", "sakura")
private val ANIME = setOf("wallcity", "ninjavillage", "redclouds", "grassroute", "spiritforest", "skyisland", "tournament",
    "pirates", "wisteria", "moonprincess", "neotokyo", "comet", "torii", "bathhouse", "fuji", "ramenalley", "schoolroof")

private val SPACE = setOf("cosmos", "moon", "ringplanet", "redplanet", "iceplanet", "lavaplanet", "earthorbit",
    "twinsuns", "nebula", "asteroids", "blackhole", "galaxy", "battlestation", HYPERSPACE, ULTRA_HYPERSPACE)
private val AIR_ONLY = setOf("sky", "skyisland")
private val LAND_ONLY = setOf("deepsea")

/** Vehicle types a banner suits: land (road), air, space - same table as the server. */
fun bannerKinds(key: String): Set<String> = when (key) {
    in SPACE -> setOf("space")
    in AIR_ONLY -> setOf("air")
    in LAND_ONLY -> setOf("land")
    else -> setOf("land", "air")       // landscapes also work as sky for planes (no road)
}

/** Picker sections: classic / pastel / anime / space. */
val BANNER_GROUPS: List<Pair<String, List<String>>> = listOf(
    "classic" to BANNERS.filter { it !in PASTEL && it !in ANIME && it !in SPACE },
    "pastel" to BANNERS.filter { it in PASTEL },
    "anime" to BANNERS.filter { it in ANIME },
    "space" to BANNERS.filter { it in SPACE },
)

fun isBanner(key: String?) = key != null && key in DEFS

/** The banner used when none is chosen: the classic scene of the vehicle's category. */
fun defaultBanner(scene: Scene) = when (scene) {
    Scene.Air -> "sky"
    Scene.Space -> "cosmos"
    else -> "dusk"
}

private class Particle(val x: Float, val y: Float, val speed: Float, val seed: Float)

/**
 * @param road draw the road (land vehicles stand on its top edge, [groundDp] above the bottom)
 */
@Composable
fun BannerBackground(
    key: String?, modifier: Modifier = Modifier, groundDp: Float = 0f, road: Boolean = groundDp > 0f,
    still: Boolean = false,          // thumbnails / avatars: no animation
) {
    val def = DEFS[key] ?: DEFS.getValue("dusk")
    val s2 = pixelScale(2f)
    val s3 = pixelScale(3f)
    val far = def.far?.let { rememberAsset(it.ifEmpty { "banners/${def.key}_far.png" }) }
    val near = def.near?.let { rememberAsset(it.ifEmpty { "banners/${def.key}_near.png" }) }
    val skyImg = if (def.sky != null) def.skyImg?.let { rememberAsset(it.ifEmpty { "banners/${def.key}_sky.png" }) } else null
    val cloud = if (def.fx == Fx.Clouds) rememberAsset("icons/scene_cloud.png") else null
    val rain = if (def.fx == Fx.Rain || def.fx == Fx.Storm) rememberAsset("icons/scene_rain.png") else null
    val parts = remember(def.key) {
        val r = Random(def.key.hashCode())
        List(when (def.fx) { Fx.Birds -> 5; Fx.Butterflies -> 7; Fx.Warp -> 120; else -> 60 }) { Particle(r.nextFloat(), r.nextFloat(), .5f + r.nextFloat(), r.nextFloat() * 6.28f) }
    }
    val clock = if (still) remember { androidx.compose.runtime.mutableFloatStateOf(3f) } else rememberClock()

    Box(modifier) {
        Spacer(Modifier.matchParentSize().drawWithCache {
            onDrawBehind {
                def.bands.forEachIndexed { i, (start, color) ->
                    val end = if (i + 1 < def.bands.size) def.bands[i + 1].first else 1f
                    drawRect(color, Offset(0f, start * size.height), Size(size.width, (end - start) * size.height + 1))
                }
            }
        })
        Canvas(Modifier.matchParentSize().graphicsLayer()) {
            val t = clock.value
            val dp = density
            val ground = if (road) size.height - groundDp * dp else size.height
            // small cards (thumbnails, avatars) get smaller art pixels so the sky stays visible
            val k = ((ground / dp) / 260f).coerceIn(.3f, 1f)
            val s = maxOf(1, kotlin.math.round(def.dpPerPx * dp * k).toInt())
            // sky object
            if (skyImg != null) when (val o = def.sky) {
                SkyObj.High -> tileX(skyImg, s, 4 * dp, phase(t, 60_000))
                is SkyObj.At -> blit(skyImg, o.x * size.width - skyImg.width * s / 2f,
                    minOf(o.y * size.height, ground - (far?.height ?: 0) * s - skyImg.height * s), s, .95f)
                is SkyObj.Horizon -> blit(skyImg, o.x * size.width - skyImg.width * s / 2f,
                    ground - (far?.height ?: 0) * s / 2f - skyImg.height * s, s)
                null -> {}
            }
            if (cloud != null) {
                tileX(cloud, s3, size.height * .12f, phase(t, 9_000), .85f)
                tileX(cloud, s2, size.height * .40f, phase(t, 5_000), .5f)
            }
            if (def.fx == Fx.Stars) parts.forEach { p ->
                if (p.y > .62f) return@forEach
                val a = .35f + .45f * (.5f + .5f * sin(t * p.speed * 2 + p.seed))
                val d = if (p.speed > 1.3f) 2 * dp else 1.3f * dp
                drawRect(Color.White.copy(alpha = a), Offset(p.x * size.width, p.y * size.height), Size(d, d))
            }
            if (def.fx == Fx.Birds) parts.forEachIndexed { i, p ->
                val x = (1f - phase(t + p.seed * 3, (14_000 / p.speed).toInt())) * (size.width + 40 * dp) - 20 * dp
                val y = size.height * (.15f + p.y * .25f) + sin(t * 2 + p.seed) * 3 * dp
                val flap = if (sin(t * 8 + i) > 0) 2 * dp else 0f
                drawRect(Color(0xCC2E2F63), Offset(x - 4 * dp, y - flap), Size(4 * dp, 2 * dp))
                drawRect(Color(0xCC2E2F63), Offset(x, y - flap), Size(4 * dp, 2 * dp))
                drawRect(Color(0xCC2E2F63), Offset(x - 1 * dp, y + 1 * dp), Size(2 * dp, 2 * dp))
            }
            // landscape (scrolls: far slow, near faster)
            if (far != null) tileX(far, s, ground - far.height * s, phase(t, 40_000))
            if (near != null) tileX(near, s, ground - near.height * s, phase(t, 16_000))

            // weather / particles
            when (def.fx) {
                Fx.Snow -> parts.forEach { p ->
                    val y = (p.y + t * .05f * p.speed) % 1f
                    val x = p.x * size.width + sin(t * p.speed + p.seed) * 8 * dp
                    drawRect(Color.White.copy(alpha = .85f), Offset(x, y * size.height), Size(2 * dp * p.speed.coerceAtMost(1.2f), 2 * dp))
                }
                Fx.Petals, Fx.Leaves -> parts.take(28).forEachIndexed { i, p ->
                    val y = (p.y + t * .04f * p.speed) % 1f
                    val x = ((p.x + t * .02f) % 1f) * size.width + sin(t * 1.5f + p.seed) * 14 * dp
                    val c = if (def.fx == Fx.Petals) (if (i % 3 == 0) Color(0xFFFFF0F6) else Color(0xFFFFB0CF))
                    else listOf(Color(0xFFE0832F), Color(0xFFB13E53), Color(0xFFFFCD75))[i % 3]
                    val wobble = sin(t * 3 + p.seed) > 0
                    drawRect(c, Offset(x, y * size.height), Size(if (wobble) 3 * dp else 2 * dp, if (wobble) 2 * dp else 3 * dp))
                }
                Fx.Embers -> parts.take(30).forEach { p ->
                    val k = (p.y + t * .06f * p.speed) % 1f              // 0 = bottom, 1 = top
                    val x = p.x * size.width + sin(t + p.seed) * 6 * dp
                    val c = if (p.speed > 1f) Color(0xFFFFCD75) else Color(0xFFEF7D57)
                    drawRect(c.copy(alpha = 1f - k), Offset(x, ground - k * ground), Size(2 * dp, 2 * dp))
                }
                Fx.Fireflies -> parts.take(18).forEach { p ->
                    val a = (sin(t * p.speed * 1.7f + p.seed) * .5f + .5f).let { it * it }
                    val x = p.x * size.width + sin(t * .3f + p.seed) * 16 * dp
                    val y = ground - (.08f + p.y * .45f) * ground + sin(t * .5f + p.seed * 2) * 8 * dp
                    drawRect(Color(0xFFE8FF8A).copy(alpha = a), Offset(x, y), Size(2 * dp, 2 * dp))
                    drawRect(Color(0xFFE8FF8A).copy(alpha = a * .25f), Offset(x - dp, y - dp), Size(4 * dp, 4 * dp))
                }
                Fx.Bubbles -> parts.take(22).forEach { p ->
                    val k = (p.y + t * .05f * p.speed) % 1f
                    val x = p.x * size.width + sin(t * 2 + p.seed) * 4 * dp
                    val y = size.height - k * size.height
                    val d = (2 + (p.speed * 2).toInt()) * dp
                    val c = Color(0x99BFE8FF)
                    drawRect(c, Offset(x, y), Size(d, dp))
                    drawRect(c, Offset(x, y + d - dp), Size(d, dp))
                    drawRect(c, Offset(x, y), Size(dp, d))
                    drawRect(c, Offset(x + d - dp, y), Size(dp, d))
                }
                Fx.Sparkles -> parts.take(26).forEachIndexed { i, p ->
                    val a = (sin(t * p.speed * 2.2f + p.seed) * .5f + .5f).let { it * it * it }
                    if (a < .05f) return@forEachIndexed
                    val c = listOf(Color(0xFFFFFFFF), Color(0xFFFFD6F0), Color(0xFFD6E4FF), Color(0xFFFFF3B0))[i % 4].copy(alpha = a)
                    val x = p.x * size.width
                    val y = p.y * ground * .9f
                    val arm = (1 + (p.speed * 1.5f).toInt()) * dp
                    drawRect(c, Offset(x, y), Size(dp * 1.5f, dp * 1.5f))
                    drawRect(c.copy(alpha = a * .7f), Offset(x - arm, y), Size(arm * 2 + dp * 1.5f, dp))
                    drawRect(c.copy(alpha = a * .7f), Offset(x, y - arm), Size(dp, arm * 2 + dp * 1.5f))
                }
                Fx.Hearts -> parts.take(14).forEachIndexed { i, p ->
                    val k = (p.y + t * .045f * p.speed) % 1f                // rising and fading
                    val x = p.x * size.width + sin(t * 1.3f + p.seed) * 10 * dp
                    val y = ground - k * ground
                    val c = (if (i % 3 == 0) Color(0xFFFFFFFF) else Color(0xFFFF5C9A)).copy(alpha = (1f - k) * .9f)
                    val u = (if (p.speed > 1.1f) 2f else 1.5f) * dp
                    listOf("01010", "11111", "01110", "00100").forEachIndexed { ry, row ->
                        row.forEachIndexed { rx, on -> if (on == '1') drawRect(c, Offset(x + rx * u, y + ry * u), Size(u, u)) }
                    }
                }
                Fx.Butterflies -> parts.forEachIndexed { i, p ->
                    val x = ((p.x + t * .015f * p.speed) % 1f) * size.width
                    val y = ground * (.35f + p.y * .5f) + sin(t * 2f + p.seed) * 10 * dp
                    val open = sin(t * 14f + p.seed) > 0
                    val c = listOf(Color(0xFFFF8FB8), Color(0xFFFFF0A0), Color(0xFFC8A8FF), Color(0xFF9FD0FF))[i % 4]
                    val w = if (open) 3 * dp else 1.5f * dp
                    drawRect(c, Offset(x - w, y), Size(w, 3 * dp))
                    drawRect(c, Offset(x + dp, y), Size(w, 3 * dp))
                    drawRect(Color(0xFF3B2558), Offset(x, y), Size(dp, 3 * dp))
                }
                Fx.Warp -> {
                    val hc = if (def.key == ULTRA_HYPERSPACE) GOLD_COLORS else HYPER_COLORS
                    // hyperspace, in the colors of the shining word: breathing nebula glows ...
                    val pulse = sin(t * 1.4f) * .5f + .5f
                    drawRect(Brush.radialGradient(listOf(hc[2].copy(alpha = .22f + pulse * .16f), Color.Transparent),
                        Offset(size.width * .8f, size.height * .4f), size.width * .6f))
                    drawRect(Brush.radialGradient(listOf(hc[1].copy(alpha = .2f + (1 - pulse) * .12f), Color.Transparent),
                        Offset(size.width * .15f, size.height * .75f), size.width * .55f))
                    drawRect(Brush.radialGradient(listOf(hc[0].copy(alpha = .1f + pulse * .08f), Color.Transparent),
                        Offset(size.width * .5f, size.height * .5f), size.width * .35f))
                    // ... streaks rushing from right to left past the ship: white head, colored glowing tail
                    parts.forEachIndexed { i, p ->
                        val k = (p.x + t * .85f * p.speed) % 1f
                        val len = (30 + p.speed * 90) * dp
                        val x = size.width + len - k * (size.width + 2 * len)
                        val y = p.y * size.height
                        val c = hc[i % 3]
                        val a = (.3f + p.speed * .45f).coerceAtMost(1f)
                        val w = (1f + (p.speed - .5f) * 2f) * dp
                        drawLine(c.copy(alpha = a * .22f), Offset(x, y), Offset(x + len * .8f, y), strokeWidth = w * 4)
                        drawLine(Brush.horizontalGradient(listOf(Color.White.copy(alpha = a), c.copy(alpha = a), Color.Transparent), x, x + len),
                            Offset(x, y), Offset(x + len, y), strokeWidth = w)
                    }
                    // ... a shine sweeping across every 3.2 s ...
                    val sx = -size.width * .6f + phase(t, 3200) * size.width * 2.2f
                    drawRect(Brush.linearGradient(listOf(Color.Transparent, hc[0].copy(alpha = .16f), Color.White.copy(alpha = .22f),
                        hc[2].copy(alpha = .16f), Color.Transparent), Offset(sx, 0f), Offset(sx + size.width * .4f, size.height)))
                    // ... and twinkling pixel sparkles
                    parts.take(18).forEachIndexed { i, p ->
                        val a = (sin(t * p.speed * 2.6f + p.seed) * .5f + .5f).let { it * it * it }
                        if (a < .08f) return@forEachIndexed
                        val c = (if (i % 2 == 0) Color.White else hc[(i / 2) % 3]).copy(alpha = a)
                        val x = ((p.seed / 6.28f + p.y * .5f) % 1f) * size.width
                        val y = ((p.x + p.seed * .1f) % 1f) * size.height
                        val arm = (2 + (p.speed * 1.5f).toInt()) * dp
                        drawRect(c, Offset(x, y), Size(2 * dp, 2 * dp))
                        drawRect(c.copy(alpha = a * .6f), Offset(x - arm, y + dp / 2), Size(arm * 2 + 2 * dp, dp))
                        drawRect(c.copy(alpha = a * .6f), Offset(x + dp / 2, y - arm), Size(dp, arm * 2 + 2 * dp))
                    }
                }
                Fx.Rain -> rain?.let { tileAll(it, s3, phase(t, 900), .45f) }
                Fx.Storm -> {
                    rain?.let { tileAll(it, s3, phase(t, 700), .5f) }
                    val f = phase(t, 7_000)
                    if (f < .02f || f in .05f..0.065f) drawRect(Color.White.copy(alpha = .35f))
                }
                else -> {}
            }
            if (road) {
                drawRect(Color(0xFF2A2F45), Offset(0f, ground), Size(size.width, 6 * dp))
                drawRect(Color(0xFF1A1C2C), Offset(0f, ground + 6 * dp), Size(size.width, size.height))
                val dash = 32 * dp
                var x = -phase(t, 450) * dash
                while (x < size.width) {
                    drawRect(Color(0x8CFFCD75), Offset(x, ground + 30 * dp), Size(dash / 2, 4 * dp))
                    x += dash
                }
            }
        }
        Spacer(Modifier.matchParentSize().drawWithCache {
            val brush = ditherBrush(density)
            onDrawBehind { drawRect(brush) }
        })
    }
}


/** Grid of all banners; [allowAuto] adds "automatic" (the vehicle's own scene, key = null). */
@Composable
fun BannerPicker(
    selected: String?, allowAuto: Boolean, autoKey: String = "dusk",
    hyperspace: Boolean? = null,        // own vehicle: null = not offered, false = locked, true = unlocked
    ultra: Boolean = false,             // the secret golden one: only listed once unlocked
    kind: String? = null,               // own vehicle type (land / air / space): only fitting banners
    onDismiss: () -> Unit, onPick: (String?) -> Unit,
) {
    val S = LocalStrings.current
    PxSheet(onDismiss) {
        androidx.compose.material3.Text(S.chooseBanner, style = T.title.copy(fontSize = 20.sp))
        // section header = String entry starting with "#"
        val first: List<String?> = (if (ultra) listOf<String?>(ULTRA_HYPERSPACE) else emptyList()) +
            (if (hyperspace != null) listOf<String?>(HYPERSPACE) else emptyList()) +
            (if (allowAuto) listOf<String?>(null) else emptyList())
        val options: List<String?> = first + BANNER_GROUPS.flatMap { (g, keys) ->
            val fitting = if (kind == null) keys else keys.filter { kind in bannerKinds(it) }
            if (fitting.isEmpty()) emptyList() else listOf<String?>("#$g") + fitting
        }
        androidx.compose.foundation.lazy.grid.LazyVerticalGrid(
            androidx.compose.foundation.lazy.grid.GridCells.Fixed(2),
            Modifier.heightIn(max = 520.dp),
            horizontalArrangement = Arrangement.spacedBy(10.dp), verticalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            items(options.size, span = { i ->
                androidx.compose.foundation.lazy.grid.GridItemSpan(if (options[i]?.startsWith("#") == true) maxLineSpan else 1)
            }) { i ->
                val key = options[i]
                if (key?.startsWith("#") == true) {
                    Label(S.bannerGroup(key.drop(1)).uppercase(), Modifier.padding(top = 10.dp, bottom = 2.dp))
                    return@items
                }
                val on = key == selected
                val locked = key == HYPERSPACE && hyperspace != true
                Box(
                    Modifier.fillMaxWidth().height(96.dp).clip(RoundedCornerShape(16.dp))
                        .then(if (on) Modifier.border(2.dp, Px.Yellow, RoundedCornerShape(16.dp)) else Modifier)
                        .clickable(enabled = !locked) { onPick(key) },
                ) {
                    BannerBackground(key ?: autoKey, Modifier.matchParentSize(), still = locked)
                    if (locked) {
                        Box(Modifier.matchParentSize().background(Color(0xB3000000)), contentAlignment = Alignment.Center) {
                            androidx.compose.foundation.layout.Row(verticalAlignment = Alignment.CenterVertically) {
                                PixelIcon("ui_lock", 16.dp)
                                androidx.compose.material3.Text("  " + S.hyperspaceLocked, style = T.small.copy(color = Px.Text))
                            }
                        }
                    }
                    HyperText(
                        if (key == null) S.bannerAuto else S.bannerName(key),
                        style = T.small.copy(color = Px.Text, fontSize = 12.sp),
                        modifier = Modifier.align(Alignment.BottomStart).background(Color(0x99000000), RoundedCornerShape(topEnd = 8.dp))
                            .padding(horizontal = 8.dp, vertical = 3.dp),
                    )
                }
            }
        }
    }
}
