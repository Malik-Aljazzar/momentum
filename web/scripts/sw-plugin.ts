// Vite plugin: writes dist/sw.js - precaches the built app (+ sprites, fonts) under a cache named
// after the build, serves it cache-first, keeps /api, /media and /avatars on the network. Encrypted chat
// notifications are opened with src/swpush.ts, bundled in (the same crypto code as the app).
import type { Plugin } from "vite"
import { buildSync } from "esbuild"
import { readFileSync } from "node:fs"
import { join } from "node:path"

export function serviceWorker(build: string): Plugin {
  return {
    name: "momentum-sw",
    apply: "build",
    generateBundle(_, bundle) {
      const extra = (JSON.parse(readFileSync(join(__dirname, "..", "src", "precache.gen.json"), "utf8")) as { assets: string[] }).assets
      const files = [...Object.keys(bundle).filter((f) => !f.endsWith(".map")), ...extra, "manifest.webmanifest", "icon-192.png", "icon-512.png"]
      const urls = ["/app/", ...files.map((f) => "/app/" + f)]
      const push = buildSync({
        entryPoints: [join(__dirname, "..", "src", "swpush.ts")], bundle: true, write: false, format: "iife",
        globalName: "momentumPush", target: "es2020", minify: true,
      }).outputFiles[0].text
      const source = `// generated by scripts/sw-plugin.ts
${push}
const CACHE = "momentum-${build}"
const PRECACHE = ${JSON.stringify(urls)}
// every file checked with the server ("no-cache": a 304 when unchanged), never taken from the browser's HTTP cache
// as it is (sprites are public for 12 h): a new build could keep 5-frame vehicle sheets from before the 8-frame
// ones, and the vehicles blinked everywhere in the app
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "no-cache" }))))
    .then(() => self.skipWaiting()))
})
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("momentum-") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()))
})
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url)
  if (e.request.method !== "GET" || url.origin !== location.origin || !url.pathname.startsWith("/app/")) return
  // the app's own files: from the cache (offline start); unknown paths inside the app -> index
  e.respondWith(caches.open(CACHE).then(async (c) => {
    const hit = await c.match(e.request, { ignoreSearch: true })
    if (hit) return hit
    try {
      return await fetch(e.request)
    } catch (err) {
      if (e.request.mode === "navigate") return (await c.match("/app/")) || Response.error()
      throw err
    }
  }))
})
// Web Push (installed PWA): show the notification, a tap opens the app at the right place; an encrypted
// message's text is opened here with the key on the phone (the server only sent the fallback text)
self.addEventListener("push", (e) => {
  let data = {}
  try { data = e.data ? e.data.json() : {} } catch (err) { data = { title: "Momentum", body: e.data ? e.data.text() : "" } }
  // a call rings in rounds (server/calls.py RING_AGAIN): every round is a notification of its own - an iPhone sounds
  // and buzzes only for a new one, not for a replaced one - and the call's earlier ones (rounds, ringing) are closed
  const tag = data.call && data.ring ? data.tag + "-" + (data.round || 0) : data.tag
  const show = (body) => self.registration.showNotification(data.title || "Momentum", {
    body: body || "", icon: "/app/icon-192.png", badge: "/app/icon-192.png", tag, data: { url: data.url || "/app/" },
    // ringing (Android Chrome; iOS ignores these): stays until tapped, buzzes
    requireInteraction: !!data.ring, renotify: !!data.ring, vibrate: data.ring ? [500, 250, 500, 250, 500] : undefined,
  })
  const shown = data.e2e ? momentumPush.pushText(data.e2e).catch(() => null).then((text) => show(text || data.body)) : show(data.body)
  e.waitUntil(data.call ? shown.then(() => callShown(data.call, tag)) : shown)
})
// a call's notification is up: its other ones closed, an open app told (it clears what it no longer rings for: calls.ts)
async function callShown(id, keep) {
  try {
    const base = "call-" + id
    for (const n of await self.registration.getNotifications()) {
      if (n.tag !== keep && (n.tag === base || n.tag.startsWith(base + "-"))) n.close()
    }
    for (const w of await self.clients.matchAll({ type: "window", includeUncontrolled: true })) w.postMessage({ type: "call-push", call: id })
  } catch (err) { /* the notification is shown, that's what counts */ }
}
self.addEventListener("notificationclick", (e) => {
  e.notification.close()
  const target = (e.notification.data && e.notification.data.url) || "/app/"
  e.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
    for (const w of list) if (w.url.includes("/app/")) {
      // (without navigate the app opens as it was - its call socket still brings the ringing)
      try { w.navigate(target).catch(() => {}) } catch (err) { /* no navigate */ }
      return w.focus()
    }
    return self.clients.openWindow(target)
  }))
})
`
      this.emitFile({ type: "asset", fileName: "sw.js", source })
    },
  }
}
