export const isBanner = (key?: string | null) => !!key && key in DEFS

/** The banner used when none is chosen: the classic scene of the vehicle's category. */
export const defaultBanner = (category: string) => (category === "air" ? "sky" : category === "space" ? "cosmos" : "dusk")

const particles = new Map<string, { x: number; y: number; speed: number; seed: number }[]>()
function partsFor(key: string, fx: Fx) {
  let p = particles.get(key)
  if (!p) {
    const r = rng(hash(key))
    p = Array.from({ length: fx === "birds" ? 5 : fx === "butterflies" ? 7 : fx === "warp" ? 120 : 60 },
      () => ({ x: r(), y: r(), speed: .5 + r(), seed: r() * 6.28 }))
    particles.set(key, p)
  }
  return p
}

const layer = (def: Def, key: string, v: string | null, kind: string) =>
  v == null ? null : sprite(v === "" ? `banners/${key}_${kind}.png` : v)

/** A soft round glow (nebula). */
export function glow(c: Ctx, x: number, y: number, r: number, color: string) {
  const g = c.g.createRadialGradient(x, y, 0, x, y, r)
  g.addColorStop(0, color); g.addColorStop(1, "rgba(0,0,0,0)")
  c.g.fillStyle = g; c.g.fillRect(0, 0, c.w, c.h)
}

/** @param groundDp road height (land vehicles stand on its top edge); 0 = no road. */
export function drawBanner(c: Ctx, keyIn: string | null | undefined, groundDp = 0) {
  const key = keyIn && keyIn in DEFS ? keyIn : "dusk"
  const def = DEFS[key]
  const dp = c.dp, t = c.t
  const s2 = pixelScale(2), s3 = pixelScale(3)
  const far = layer(def, key, def.far, "far")
  const near = layer(def, key, def.near, "near")
  const skyImg = def.sky ? layer(def, key, def.skyImg, "sky") : null
  const parts = partsFor(key, def.fx)
  const road = groundDp > 0
  const ground = road ? c.h - groundDp * dp : c.h
  // small cards (thumbnails, avatars) get smaller art pixels so the sky stays visible
  const k = Math.min(1, Math.max(.3, ground / dp / 260))
  const s = Math.max(1, Math.round(def.dpPerPx * dp * k))
  const farH = (far?.naturalHeight ?? 0) * s

  drawBands(c, def.bands)
  if (skyImg && def.sky) {
    if (def.sky.kind === "high") tileX(c, skyImg, s, 4 * dp, phase(t, 60_000))
    else if (def.sky.kind === "at") blit(c, skyImg, def.sky.x * c.w - skyImg.naturalWidth * s / 2,
      Math.min(def.sky.y * c.h, ground - farH - skyImg.naturalHeight * s), s, .95)
    else blit(c, skyImg, def.sky.x * c.w - skyImg.naturalWidth * s / 2, ground - farH / 2 - skyImg.naturalHeight * s, s)
  }
  if (def.fx === "clouds") {
    const cloud = sprite("icons/scene_cloud.png")
    tileX(c, cloud, s3, c.h * .12, phase(t, 9_000), .85)
    tileX(c, cloud, s2, c.h * .40, phase(t, 5_000), .5)
  }
  if (def.fx === "stars") for (const p of parts) {
    if (p.y > .62) continue
    const a = .35 + .45 * (.5 + .5 * Math.sin(t * p.speed * 2 + p.seed))
    const d = p.speed > 1.3 ? 2 * dp : 1.3 * dp
    rect(c, `rgba(255,255,255,${a})`, p.x * c.w, p.y * c.h, d, d)
  }
  if (def.fx === "birds") parts.forEach((p, i) => {
    const x = (1 - phase(t + p.seed * 3, 14_000 / p.speed)) * (c.w + 40 * dp) - 20 * dp
    const y = c.h * (.15 + p.y * .25) + Math.sin(t * 2 + p.seed) * 3 * dp
    const flap = Math.sin(t * 8 + i) > 0 ? 2 * dp : 0
    const col = "rgba(46,47,99,0.8)"
    rect(c, col, x - 4 * dp, y - flap, 4 * dp, 2 * dp)
    rect(c, col, x, y - flap, 4 * dp, 2 * dp)
    rect(c, col, x - dp, y + dp, 2 * dp, 2 * dp)
  })
  // landscape (scrolls: far slow, near faster)
  if (far) tileX(c, far, s, ground - far.naturalHeight * s, phase(t, 40_000))
  if (near) tileX(c, near, s, ground - near.naturalHeight * s, phase(t, 16_000))

  switch (def.fx) {
    case "snow": for (const p of parts) {
      const y = (p.y + t * .05 * p.speed) % 1
      const x = p.x * c.w + Math.sin(t * p.speed + p.seed) * 8 * dp
      rect(c, "rgba(255,255,255,0.85)", x, y * c.h, 2 * dp * Math.min(p.speed, 1.2), 2 * dp)
    } break
    case "petals": case "leaves": parts.slice(0, 28).forEach((p, i) => {
      const y = (p.y + t * .04 * p.speed) % 1
      const x = ((p.x + t * .02) % 1) * c.w + Math.sin(t * 1.5 + p.seed) * 14 * dp
      const col = def.fx === "petals" ? (i % 3 === 0 ? "#FFF0F6" : "#FFB0CF") : ["#E0832F", "#B13E53", "#FFCD75"][i % 3]
      const wob = Math.sin(t * 3 + p.seed) > 0
      rect(c, col, x, y * c.h, wob ? 3 * dp : 2 * dp, wob ? 2 * dp : 3 * dp)
    }); break
    case "embers": for (const p of parts.slice(0, 30)) {
      const kk = (p.y + t * .06 * p.speed) % 1              // 0 = bottom, 1 = top
      const x = p.x * c.w + Math.sin(t + p.seed) * 6 * dp
      c.g.globalAlpha = 1 - kk
      rect(c, p.speed > 1 ? "#FFCD75" : "#EF7D57", x, ground - kk * ground, 2 * dp, 2 * dp)
      c.g.globalAlpha = 1
    } break
    case "fireflies": for (const p of parts.slice(0, 18)) {
      const a = (Math.sin(t * p.speed * 1.7 + p.seed) * .5 + .5) ** 2
      const x = p.x * c.w + Math.sin(t * .3 + p.seed) * 16 * dp
      const y = ground - (.08 + p.y * .45) * ground + Math.sin(t * .5 + p.seed * 2) * 8 * dp
      rect(c, `rgba(232,255,138,${a})`, x, y, 2 * dp, 2 * dp)
      rect(c, `rgba(232,255,138,${a * .25})`, x - dp, y - dp, 4 * dp, 4 * dp)
    } break
    case "bubbles": for (const p of parts.slice(0, 22)) {
      const kk = (p.y + t * .05 * p.speed) % 1
      const x = p.x * c.w + Math.sin(t * 2 + p.seed) * 4 * dp
      const y = c.h - kk * c.h
      const d = (2 + Math.floor(p.speed * 2)) * dp
      const col = "rgba(191,232,255,0.6)"
      rect(c, col, x, y, d, dp); rect(c, col, x, y + d - dp, d, dp); rect(c, col, x, y, dp, d); rect(c, col, x + d - dp, y, dp, d)
    } break
    case "sparkles": parts.slice(0, 26).forEach((p, i) => {
      const a = (Math.sin(t * p.speed * 2.2 + p.seed) * .5 + .5) ** 3
      if (a < .05) return
      const col = ["255,255,255", "255,214,240", "214,228,255", "255,243,176"][i % 4]
      const x = p.x * c.w, y = p.y * ground * .9
      const arm = (1 + Math.floor(p.speed * 1.5)) * dp
      rect(c, `rgba(${col},${a})`, x, y, dp * 1.5, dp * 1.5)
      rect(c, `rgba(${col},${a * .7})`, x - arm, y, arm * 2 + dp * 1.5, dp)
      rect(c, `rgba(${col},${a * .7})`, x, y - arm, dp, arm * 2 + dp * 1.5)
    }); break
    case "hearts": parts.slice(0, 14).forEach((p, i) => {
      const kk = (p.y + t * .045 * p.speed) % 1                // rising and fading
      const x = p.x * c.w + Math.sin(t * 1.3 + p.seed) * 10 * dp
      const y = ground - kk * ground
      const col = `rgba(${i % 3 === 0 ? "255,255,255" : "255,92,154"},${(1 - kk) * .9})`
      const u = (p.speed > 1.1 ? 2 : 1.5) * dp
      ;["01010", "11111", "01110", "00100"].forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) if (row[rx] === "1") rect(c, col, x + rx * u, y + ry * u, u, u)
      })
    }); break
    case "butterflies": parts.forEach((p, i) => {
      const x = ((p.x + t * .015 * p.speed) % 1) * c.w
      const y = ground * (.35 + p.y * .5) + Math.sin(t * 2 + p.seed) * 10 * dp
      const open = Math.sin(t * 14 + p.seed) > 0
      const col = ["#FF8FB8", "#FFF0A0", "#C8A8FF", "#9FD0FF"][i % 4]
      const w = open ? 3 * dp : 1.5 * dp
      rect(c, col, x - w, y, w, 3 * dp); rect(c, col, x + dp, y, w, 3 * dp); rect(c, "#3B2558", x, y, dp, 3 * dp)
    }); break
    case "warp": {
      // hyperspace, in the colors of the shining word (golden for ultra): breathing nebula glows ...
      const hc = key === ULTRA_HYPERSPACE ? GOLD_RGB : HYPER_RGB
      const col = (k: number, a: number) => `rgba(${hc[k]},${a})`
      const pulse = Math.sin(t * 1.4) * .5 + .5
      glow(c, c.w * .8, c.h * .4, c.w * .6, col(2, .22 + pulse * .16))
      glow(c, c.w * .15, c.h * .75, c.w * .55, col(1, .2 + (1 - pulse) * .12))
      glow(c, c.w * .5, c.h * .5, c.w * .35, col(0, .1 + pulse * .08))
      // ... streaks rushing from right to left past the ship: white head, colored glowing tail ...
      parts.forEach((p, i) => {
        const kk = (p.x + t * .85 * p.speed) % 1
        const len = (30 + p.speed * 90) * dp
        const x = c.w + len - kk * (c.w + 2 * len)
        const y = p.y * c.h
        const a = Math.min(1, .3 + p.speed * .45)
        const w = (1 + (p.speed - .5) * 2) * dp
        c.g.strokeStyle = col(i % 3, a * .22)
        c.g.lineWidth = w * 4
        c.g.beginPath(); c.g.moveTo(x, y); c.g.lineTo(x + len * .8, y); c.g.stroke()
        const gr = c.g.createLinearGradient(x, 0, x + len, 0)
        gr.addColorStop(0, `rgba(255,255,255,${a})`); gr.addColorStop(.5, col(i % 3, a)); gr.addColorStop(1, col(i % 3, 0))
        c.g.strokeStyle = gr
        c.g.lineWidth = w
        c.g.beginPath(); c.g.moveTo(x, y); c.g.lineTo(x + len, y); c.g.stroke()
      })
      // ... a shine sweeping across every 3.2 s ...
      const sx = -c.w * .6 + phase(t, 3200) * c.w * 2.2
      const sg = c.g.createLinearGradient(sx, 0, sx + c.w * .4, c.h)
      sg.addColorStop(0, "rgba(0,0,0,0)"); sg.addColorStop(.3, col(0, .16)); sg.addColorStop(.5, "rgba(255,255,255,.22)")
      sg.addColorStop(.7, col(2, .16)); sg.addColorStop(1, "rgba(0,0,0,0)")
      c.g.fillStyle = sg; c.g.fillRect(0, 0, c.w, c.h)
      // ... and twinkling pixel sparkles
      parts.slice(0, 18).forEach((p, i) => {
        const a = (Math.sin(t * p.speed * 2.6 + p.seed) * .5 + .5) ** 3
        if (a < .08) return
        const color = i % 2 === 0 ? `rgba(255,255,255,${a})` : col((i >> 1) % 3, a)
        const x = ((p.seed / 6.28 + p.y * .5) % 1) * c.w
        const y = ((p.x + p.seed * .1) % 1) * c.h
        const arm = (2 + Math.floor(p.speed * 1.5)) * dp
        rect(c, color, x, y, 2 * dp, 2 * dp)
        c.g.globalAlpha = .6
        rect(c, color, x - arm, y + dp / 2, arm * 2 + 2 * dp, dp)
        rect(c, color, x + dp / 2, y - arm, dp, arm * 2 + 2 * dp)
        c.g.globalAlpha = 1
      })
    } break
    case "rain": tileAll(c, sprite("icons/scene_rain.png"), s3, phase(t, 900), .45); break
    case "storm": {
      tileAll(c, sprite("icons/scene_rain.png"), s3, phase(t, 700), .5)
      const f = phase(t, 7_000)
      if (f < .02 || (f >= .05 && f <= .065)) rect(c, "rgba(255,255,255,0.35)", 0, 0, c.w, c.h)
      break
    }
  }
  if (road) {
    rect(c, "#2A2F45", 0, ground, c.w, 6 * dp)
    rect(c, "#1A1C2C", 0, ground + 6 * dp, c.w, c.h)
    const dash = 32 * dp
    for (let x = -phase(t, 450) * dash; x < c.w; x += dash) rect(c, "rgba(255,205,117,0.55)", x, ground + 30 * dp, dash / 2, 4 * dp)
  }
  dither(c)
}
