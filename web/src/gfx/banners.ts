/** Vehicle types a banner suits: land (road), air, space - same table as the server. */
export function bannerKinds(key: string): Set<string> {
  if (SPACE.has(key)) return new Set(["space"])
  if (AIR_ONLY.has(key)) return new Set(["air"])
  if (LAND_ONLY.has(key)) return new Set(["land"])
  return new Set(["land", "air"])
}

